source('R/load.R')
packages<-c('tclust','dbscan','otrimle','teigen','robustbase','mlbench')
z<-data.frame(package=packages,available=vapply(packages,requireNamespace,logical(1),quietly=TRUE))
z$version<-vapply(packages,function(p)if(requireNamespace(p,quietly=TRUE))as.character(packageVersion(p)) else NA_character_,character(1))
print(z);dir.create('results/environment',recursive=TRUE,showWarnings=FALSE)
write.csv(z,'results/environment/packages.csv',row.names=FALSE)
writeLines(capture.output(sessionInfo()),'results/environment/session_info.txt')
if(!all(z$available[z$package%in%c('tclust','dbscan')]))stop('Core dependencies unavailable')
cat(if(all(z$available))'ALL_DEPENDENCIES_OK\n' else 'CORE_OK_OPTIONAL_DEPENDENCIES_MISSING\n')
